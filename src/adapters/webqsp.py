def import_graph_from_webqsp(
    source: Any,
    *,
    container: Optional[SimpleGraphContainer] = None,
    keep_source_reference: bool = False,
    attach_index: Optional[bool] = None,
    hf_dataset_name: str = "rmanluo/RoG-webqsp",
    **kwargs: Any,
) -> SearchableGraphContainer:
    """
    Convenience wrapper around :class:`WebQSPAdapter`.

    Args:
        source: Path to the preprocessed WebQSP dataset directory
            (containing ``nodes/``, ``edges/``, ``graphs/`` subdirectories).
        container: Optional existing container to populate.
        keep_source_reference: Store ``_source_path`` / ``_source_style`` on
            every node and edge.
        attach_index: Upsert ``.pt`` embeddings into ChromaDB.  Defaults to
            the ``GRETRIEVER_ATTACH_INDEX`` env-var (True when unset).
        hf_dataset_name: HuggingFace dataset identifier used to fetch
            questions/answers.  Defaults to ``"rmanluo/RoG-webqsp"``.
    """
    return WebQSPAdapter().import_graph(
        source=source,
        container=container,
        keep_source_reference=keep_source_reference,
        attach_index=attach_index,
        hf_dataset_name=hf_dataset_name,
        **kwargs,
    )
