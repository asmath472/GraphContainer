def _normalize_source(source: Any) -> Path:
    if isinstance(source, (str, Path)):
        return Path(source)
    raise UnsupportedSourceError(f"Unsupported source type: {type(source)}")


def _load_hf_dataset(dataset_name: str = "rmanluo/RoG-webqsp"):
    """Load and concatenate train/validation/test splits from HuggingFace."""
    try:
        from datasets import load_dataset, concatenate_datasets
    except ImportError:
        raise ImportError(
            "The 'datasets' package is required to load WebQSP questions. "
            "Install it with: pip install datasets"
        )
    dataset = load_dataset(dataset_name)
    parts = [dataset[split] for split in ("train", "validation", "test") if split in dataset]
    if not parts:
        raise UnsupportedSourceError(
            f"No expected splits found in '{dataset_name}'. Available: {list(dataset.keys())}"
        )
    return concatenate_datasets(parts) if len(parts) > 1 else parts[0]


def _generate_questions_csv(src_path: Path, dataset_name: str = "rmanluo/RoG-webqsp") -> Path:
    """
    Generate ``questions.csv`` in *src_path* by fetching questions/answers from
    HuggingFace.  Skips generation if the file already exists.

    Returns the path to the generated (or existing) ``questions.csv``.
    """
    questions_csv = src_path / "questions.csv"
    if questions_csv.exists():
        print(f"[WebQSP] questions.csv already exists at {questions_csv}, skipping generation.")
        return questions_csv

    print(f"[WebQSP] Generating questions.csv from HuggingFace '{dataset_name}' ...")

    split_dir = src_path / "split"
    split_indices: Dict[str, set] = {}
    for split_name in ("train", "val", "test"):
        fname = split_dir / f"{split_name}_indices.txt"
        if fname.exists():
            with fname.open("r") as f:
                split_indices[split_name] = {int(l.strip()) for l in f if l.strip()}

    def _get_split(idx: int) -> str:
        for split_name, indices in split_indices.items():
            if idx in indices:
                return split_name
        return "unknown"

    hf_data = _load_hf_dataset(dataset_name)

    with questions_csv.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["question", "image_id", "answer", "split"])
        for idx, row in enumerate(tqdm(hf_data, desc="Writing questions.csv")):
            question = str(row.get("question", "")).strip()
            answers = row.get("answer", [])
            if isinstance(answers, list):
                answer_str = "|".join(str(a).lower() for a in answers)
            else:
                answer_str = str(answers).lower()
            split_name = _get_split(idx)
            writer.writerow([question, str(idx), answer_str, split_name])

    print(f"[WebQSP] Wrote {len(hf_data)} questions to {questions_csv}")
    return questions_csv


