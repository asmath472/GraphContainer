"""
webqsp.py – GraphContainer adapter for the WebQSP dataset preprocessed by G-Retriever.

Dataset layout expected at *source* path
(default: dataset/webqsp/ inside the G-Retriever repo):

    nodes/{idx}.csv      – columns: node_id, node_attr
    edges/{idx}.csv      – columns: src, edge_attr, dst
    graphs/{idx}.pt      – torch_geometric Data objects with .x / .edge_attr embeddings
    split/
        train_indices.txt
        val_indices.txt
        test_indices.txt
    questions.csv        – auto-generated by this adapter on first import (if absent)
                           columns: question, image_id, answer, split

Questions and answers are sourced from the HuggingFace dataset
``rmanluo/RoG-webqsp`` (train + validation + test), concatenated in the
same order used by the G-Retriever pre-processing script.

Oracle resolution:
    The g_retriever oracle style is reused.  It maps
    ``norm(question) → image_id (= graph index)`` via ``questions.csv``,
    then loads all ``node_attr`` values from ``nodes/{image_id}.csv`` as
    gold nodes.  Because the per-question subgraph is the gold context in
    WebQSP (the graph IS the oracle), this gives exact gold-node coverage.

Usage:
    python serve.py --format webqsp --source /mnt/disk2/cjhyun/G-Retriever/dataset/webqsp
"""

